// Build the public "snow-adv" icon subset from the vendored lucide bundle.
//
// The public image ships only public_frontend/, frontend/shared/ and
// frontend/assets/immersive/, so the 400 KB vendored lucide bundle is not
// available to the public page.  This script copies just the icon node data
// the public UI uses into one small ES module.  Re-run it after changing ICONS
// or the vendored lucide version:
//
//   node App/scripts/build_snow_adv_icons.mjs
//
// The output is deterministic, so tests can verify it is up to date.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendorPath = join(appRoot, "frontend", "vendor", "lucide.min.js");
const outputPath = join(appRoot, "public_frontend", "modules", "snow-icons.js");

// kebab-case public name -> lucide export name.
export const ICONS = Object.freeze({
  bell: "Bell",
  "chevron-down": "ChevronDown",
  eye: "Eye",
  "eye-off": "EyeOff",
  "fast-forward": "FastForward",
  footprints: "Footprints",
  history: "History",
  info: "Info",
  "map-pin": "MapPin",
  menu: "Menu",
  "message-circle": "MessageCircle",
  play: "Play",
  search: "Search",
  "send-horizontal": "SendHorizontal",
  settings: "Settings",
  smile: "Smile",
  snowflake: "Snowflake",
  sparkles: "Sparkles",
  x: "X",
});

function lucideVersion(source) {
  const match = source.match(/@license lucide v([0-9.]+)/);
  if (!match) throw new Error("cannot read the vendored lucide version");
  return match[1];
}

function build() {
  const source = readFileSync(vendorPath, "utf8");
  const lucide = createRequire(import.meta.url)(vendorPath);
  const nodes = {};
  for (const [name, exportName] of Object.entries(ICONS)) {
    const node = lucide.icons?.[exportName] ?? lucide[exportName];
    if (!Array.isArray(node) || !node.length) throw new Error(`lucide icon not found: ${exportName}`);
    for (const [tag, attributes] of node) {
      if (!["path", "circle", "rect", "line", "polyline", "polygon", "ellipse"].includes(tag)) {
        throw new Error(`unsupported SVG element in ${exportName}: ${tag}`);
      }
      for (const key of Object.keys(attributes)) {
        if (!/^[a-z][a-z0-9-]*$/i.test(key) || /^on/i.test(key) || /href/i.test(key)) throw new Error(`unsafe attribute in ${exportName}: ${key}`);
      }
    }
    nodes[name] = node.map(([tag, attributes]) => [tag, Object.fromEntries(Object.entries(attributes).filter(([key]) => key !== "key"))]);
  }
  const version = lucideVersion(source);
  return `// Generated by App/scripts/build_snow_adv_icons.mjs -- do not edit by hand.
// Icon geometry from lucide v${version} (ISC License, https://lucide.dev/license).
// Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).
// All other copyright (c) for Lucide are held by Lucide Contributors 2022.
const SVG_NS = "http://www.w3.org/2000/svg";
const ICON_NODES = Object.freeze(${JSON.stringify(nodes, null, 0)});

export const SNOW_ICON_NAMES = Object.freeze(Object.keys(ICON_NODES));

/** Build a decorative inline SVG icon with DOM APIs only (CSP-safe). */
export function createSnowIcon(name, doc = document) {
  const node = ICON_NODES[name];
  if (!node) throw new Error(\`unknown snow icon: \${name}\`);
  const svg = doc.createElementNS(SVG_NS, "svg");
  for (const [key, value] of [["viewBox", "0 0 24 24"], ["fill", "none"], ["stroke", "currentColor"], ["stroke-width", "2"],
    ["stroke-linecap", "round"], ["stroke-linejoin", "round"], ["aria-hidden", "true"], ["focusable", "false"]]) svg.setAttribute(key, value);
  svg.classList.add("snow-icon", \`snow-icon-\${name}\`);
  for (const [tag, attributes] of node) {
    const child = doc.createElementNS(SVG_NS, tag);
    for (const [key, value] of Object.entries(attributes)) child.setAttribute(key, String(value));
    svg.append(child);
  }
  return svg;
}
`;
}

const output = build();
if (process.argv.includes("--check")) {
  // Compare with normalised line endings so a Windows core.autocrlf checkout passes.
  const current = readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n");
  if (current !== output) {
    console.error("public_frontend/modules/snow-icons.js is out of date; run node App/scripts/build_snow_adv_icons.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, output, "utf8");
}
